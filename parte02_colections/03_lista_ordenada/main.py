# lista de cidades
cidades = ["Rio de Janeiro", "Brasília", "São Paulo", "Goiânia", "Cuiabá"]

# ordena a lista
cidades.sort()

# exibe a lista em ordem alfabética
for cidade in cidades:
    print(cidade)

# reverte a lista
cidades.sort(reverse=True)

# exibe a lista em ordem reversa
for cidade in cidades:
    print(cidade)